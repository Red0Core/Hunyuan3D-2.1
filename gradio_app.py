@spaces.GPU(duration=60)
def _gen_shape(
    caption=None,
    image=None,
    mv_image_front=None,
    mv_image_back=None,
    mv_image_left=None,
    mv_image_right=None,
    steps=50,
    guidance_scale=7.5,
    seed=1234,
    octree_resolution=256,
    check_box_rembg=False,
    num_chunks=200000,
    randomize_seed: bool = False,
):
    # Multiview is decided per request: any view uploaded in the MultiView tab routes
    # to the multiview checkpoint, otherwise the single-image 2.1 model is used.
    mv_views = {
        'front': mv_image_front,
        'back': mv_image_back,
        'left': mv_image_left,
        'right': mv_image_right,
    }
    mv_views = {k: v for k, v in mv_views.items() if v is not None}
    use_mv = bool(mv_views)

    if not use_mv and image is None and caption is None:
        raise gr.Error("Please provide an image, or upload views in the MultiView tab.")
    if use_mv:
        image = mv_views

    seed = int(randomize_seed_fn(seed, randomize_seed))

    octree_resolution = int(octree_resolution)
    if caption: print('prompt is', caption)
    save_folder = gen_save_folder()
    stats = {
        'model': {
            'shapegen': (f'{args.mv_model_path}/{args.mv_subfolder}' if use_mv
                         else f'{args.model_path}/{args.subfolder}'),
            'texgen': f'{args.texgen_model_path}',
            'views': list(mv_views) if use_mv else ['single'],
        },
        'params': {
            'caption': caption,
            'steps': steps,
            'guidance_scale': guidance_scale,
            'seed': seed,
            'octree_resolution': octree_resolution,
            'check_box_rembg': check_box_rembg,
            'num_chunks': num_chunks,
        }
    }
    time_meta = {}

    if image is None:
        start_time = time.time()
        try:
            image = t2i_worker(caption)
        except Exception as e:
            raise gr.Error(f"Text to 3D is disable. \
            Please enable it by `python gradio_app.py --enable_t23d`.")
        time_meta['text2image'] = time.time() - start_time

    # remove disk io to make responding faster, uncomment at your will.
    # image.save(os.path.join(save_folder, 'input.png'))
    if use_mv:
        start_time = time.time()
        for k, v in image.items():
            if check_box_rembg or v.mode == "RGB":
                img = rmbg_worker(v.convert('RGB'))
                image[k] = img
        time_meta['remove background'] = time.time() - start_time
    else:
        if check_box_rembg or image.mode == "RGB":
            start_time = time.time()
            image = rmbg_worker(image.convert('RGB'))
            time_meta['remove background'] = time.time() - start_time

    # remove disk io to make responding faster, uncomment at your will.
    # image.save(os.path.join(save_folder, 'rembg.png'))

    # image to white model
    start_time = time.time()

    shape_worker = get_shape_worker(use_mv)
    use_stage('shape', shape_worker)
    generator = torch.Generator()
    generator = generator.manual_seed(int(seed))
    outputs = shape_worker(
        image=image,
        num_inference_steps=steps,
        guidance_scale=guidance_scale,
        generator=generator,
        octree_resolution=octree_resolution,
        num_chunks=num_chunks,
        output_type='mesh'
    )
    time_meta['shape generation'] = time.time() - start_time
    logger.info("---Shape generation takes %s seconds ---" % (time.time() - start_time))

    tmp_start = time.time()
    mesh = export_to_trimesh(outputs)[0]
    time_meta['export to trimesh'] = time.time() - tmp_start

    stats['number_of_faces'] = mesh.faces.shape[0]
    stats['number_of_vertices'] = mesh.vertices.shape[0]

    stats['time'] = time_meta
    if use_mv:
        # The texture stage takes a single reference; prefer the front view but fall
        # back to whichever view was supplied, since all four are optional.
        main_image = image.get('front') or next(iter(image.values()))
    else:
        main_image = image
    return mesh, main_image, save_folder, stats, seed

