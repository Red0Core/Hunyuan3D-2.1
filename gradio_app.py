# ---------------------------------------------------------------------------
# VRAM stage swapping
#
# Shape DiT (~6.9GB fp16) + paint UNet/DINOv2/ESRGAN (~5.4GB fp16) do not both
# fit on a 16GB card alongside their activations -- upstream quotes 29GB for the
# combined pipeline. The two stages never run at the same time, so park the idle
# one in system RAM. Costs a couple of seconds of PCIe transfer per switch and
# buys back ~7GB of working room, which is what lets the fast decode settings
# (bigger num_chunks, higher octree) actually run.
# ---------------------------------------------------------------------------
_ACTIVE_STAGE = None
# Shape workers, keyed by mode. 'single' (Hunyuan3D-2.1) is loaded at startup;
# 'mv' (Hunyuan3D-2mv) is loaded on first multiview request so the ~3.3GB download
# only happens for users who actually upload extra views.
_SHAPE_WORKERS = {}


def _register_legacy_module_aliases():
    """Let 2.0-era checkpoint configs load inside the 2.1 package layout.

    Hunyuan3D-2mv's config.yaml targets `hy3dgen.shapegen.*`, the package name used
    before 2.1 renamed it to `hy3dshape`. Every class it asks for still exists:
        hy3dgen.shapegen.models.Hunyuan3DDiT        -> hy3dshape.models.Hunyuan3DDiT
        hy3dgen.shapegen.models.ShapeVAE            -> hy3dshape.models.ShapeVAE
        hy3dgen.shapegen.models.SingleImageEncoder  -> hy3dshape.models.SingleImageEncoder
        ...schedulers / preprocessors / pipelines   -> same names under hy3dshape
    get_obj_from_str() resolves via importlib, so aliasing in sys.modules is enough.
    """
    import importlib
    import types

    if 'hy3dgen.shapegen' in sys.modules:
        return
    pkg = types.ModuleType('hy3dgen')
    shapegen = types.ModuleType('hy3dgen.shapegen')
    pkg.shapegen = shapegen
    sys.modules['hy3dgen'] = pkg
    sys.modules['hy3dgen.shapegen'] = shapegen
    for sub in ('models', 'schedulers', 'preprocessors', 'pipelines'):
        mod = importlib.import_module(f'hy3dshape.{sub}')
        setattr(shapegen, sub, mod)
        sys.modules[f'hy3dgen.shapegen.{sub}'] = mod


def get_shape_worker(mv: bool):
    """Return the shape pipeline for single-image or multiview conditioning.

    Hunyuan3D-2.1's checkpoint declares conditioner: SingleImageEncoder, so it cannot
    consume back/side views at all. Hunyuan3D-2mv is the multiview-conditioned
    checkpoint (DinoImageEncoderMV + MVImageProcessorV2) and accepts any subset of
    front/left/back/right. Keeping both lets one GUI serve both cases.
    """
    key = 'mv' if mv else 'single'
    if key in _SHAPE_WORKERS:
        return _SHAPE_WORKERS[key]

    if not mv:
        _SHAPE_WORKERS['single'] = i23d_worker
        return i23d_worker

    logger.info(f'Loading multiview shape model {args.mv_model_path}/{args.mv_subfolder} '
                f'(first use downloads ~4.6GB)')
    _register_legacy_module_aliases()
    worker = Hunyuan3DDiTFlowMatchingPipeline.from_pretrained(
        args.mv_model_path,
        subfolder=args.mv_subfolder,
        use_safetensors=False,
        device='cpu' if args.low_vram_mode else args.device,
    )
    if args.enable_flashvdm:
        # replace_vae=False: enable_flashvdm's turbo_vae_mapping would swap in
        # tencent/Hunyuan3D-2's decoder-only turbo VAE, which ShapeVAE.from_pretrained
        # loads strictly and rejects for missing encoder keys. The 2mv checkpoint ships
        # its own VAE; we only want the FlashVDM decoding path on top of it. (2.1 is
        # absent from that mapping, so it never hit this.)
        worker.enable_flashvdm(
            mc_algo='mc' if args.device in ['cpu', 'mps'] else args.mc_algo,
            replace_vae=False,
        )
    _SHAPE_WORKERS['mv'] = worker
    return worker


def _paint_modules():
    """nn.Modules owned by the texture pipeline that are safe to relocate."""
    if not HAS_TEXTUREGEN:
        return []
    mods = []
    mv = tex_pipeline.models.get('multiview_model')
    if mv is not None:
        mods.append(mv.pipeline)
        if hasattr(mv, 'dino_v2'):
            mods.append(mv.dino_v2)
    sm = tex_pipeline.models.get('super_model')
    if sm is not None:
        mods.append(sm.upsampler.model)
    return mods


def use_stage(stage, shape_worker=None):
    """Make `stage` ('shape' or 'paint') resident on the GPU, evict everything else.

    With two shape checkpoints available, only the one being used is promoted; the
    other stays in system RAM alongside the idle paint stack.
    """
    global _ACTIVE_STAGE
    key = stage if stage != 'shape' else f'shape:{id(shape_worker)}'
    if not args.low_vram_mode or _ACTIVE_STAGE == key:
        return
    start = time.time()
    if stage == 'shape':
        for m in _paint_modules():
            m.to('cpu')
        for w in _SHAPE_WORKERS.values():
            if w is not shape_worker:
                w.to('cpu')
        torch.cuda.empty_cache()
        shape_worker.to(args.device)
    else:
        for w in _SHAPE_WORKERS.values():
            w.to('cpu')
        torch.cuda.empty_cache()
        for m in _paint_modules():
            m.to(args.device)
    torch.cuda.empty_cache()
    _ACTIVE_STAGE = key
    logger.info(f"---Swapped to '{stage}' stage in {time.time() - start:.1f}s "
                f"({torch.cuda.memory_allocated() / 2 ** 30:.1f}GB allocated) ---")


